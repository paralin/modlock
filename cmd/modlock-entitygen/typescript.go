// typeScriptConsole writes the console module: an interface mapping each
// console variable to its value's type and one naming each command, both
// documented with the game's help text.
func typeScriptConsole(c *console) []byte {
	var out bytes.Buffer
	out.WriteString(typeScriptConsolePreamble)
	out.WriteString("\n/** Variables maps each console variable to the type of its value. */\nexport interface Variables {\n")
	for _, v := range c.variables {
		fmt.Fprintf(&out, "%s  %s: %s\n", typeScriptDoc(sentence(v.help)), v.name, v.scriptType())
	}
	out.WriteString("}\n\n/** Commands names each console command; its members' type is unused. */\nexport interface Commands {\n")
	for _, command := range c.commands {
		fmt.Fprintf(&out, "%s  %s: true\n", typeScriptDoc(sentence(command.help)), command.name)
	}
	out.WriteString("}\n")
	return out.Bytes()
}

// typeScriptTable returns an object literal of entries, each a line, as the
// formatter writes it.
func typeScriptTable(entries []string) string {
	if len(entries) == 0 {
		return "{}"
	}
	return "{\n  " + strings.Join(entries, ",\n  ") + ",\n}"
}

// typeScriptAccessor returns the getter and setter of field f of className,
// whose getter returns typ: a string is read only, angles read as a vector, a
// handle as an instance of the class it names, and a list as an array.
func typeScriptAccessor(className string, f readable, typ string) string {
	at := fmt.Sprintf("this, '%s', '%s'", className, f.name)
	var get, set string
	switch {
	case f.list:
		get = fmt.Sprintf("readFieldList(this.handle, '%s', '%s', '%s') as %s", className, f.name, f.wire, typ)
		set = fmt.Sprintf("writeFieldList(this.handle, '%s', '%s', '%s', value)", className, f.name, f.wire)
	case f.angles:
		get = fmt.Sprintf("readAngles(%s)", at)
		set = fmt.Sprintf("putAngles(%s, value)", at)
	case f.target != "":
		get = fmt.Sprintf("const target = readHandle(%s)\n    return target === undefined ? undefined : new %s(target)", at, f.target)
		set = fmt.Sprintf("putHandle(%s, value)", at)
	default:
		get = fmt.Sprintf("readField(this.handle, '%s', '%s', '%s') as %s | undefined", className, f.name, f.wire, typ)
		if f.wire != "string" {
			set = fmt.Sprintf("put(%s, '%s', value)", at, f.wire)
		}
	}
	if !strings.HasPrefix(get, "const ") {
		get = "return " + get
	}
	result := typ + " | undefined"
	if f.list {
		result = typ
	}
	accessor := fmt.Sprintf("  get %s(): %s {\n    %s\n  }\n", f.name, result, get)
	if set != "" {
		accessor += fmt.Sprintf("  set %s(value: %s) {\n    %s\n  }\n", f.name, result, set)
	}
	return accessor
}

// typeScriptInput returns the method that sends input in, with its value
// as the case of EntityValue it travels as, if it takes one.
func typeScriptInput(in input) string {
	doc := typeScriptDoc(sentence(in.description))
	if in.value == "" {
		return doc + fmt.Sprintf("  input%s(activator?: number): boolean {\n    return fireInput(this.handle, '%s', undefined, activator)\n  }\n", in.name, in.name)
	}
	return doc + fmt.Sprintf("  input%s(value: %s, activator?: number): boolean {\n    return fireInput(this.handle, '%s', { %s: value }, activator)\n  }\n", in.name, typeScriptKeyTypes[string(in.value)], in.name, in.value)
}

// typeScriptKeyTypes maps each case of EntityValue to the type of its value.
var typeScriptKeyTypes = map[string]string{
	"boolean": "boolean",
	"integer": "number",
	"number":  "number",
	"text":    "string",
	"vector":  "Vector",
	"color":   "number",
}

// typeScriptDoc returns doc as the comment of a member, wrapped when long,
// or empty for an empty doc.
func typeScriptDoc(doc string) string {
	switch {
	case doc == "":
		return ""
	case len(doc) <= 70:
		return "  /** " + doc + " */\n"
	}
	return "  /**\n" + wrap("   * ", doc) + "   */\n"
}

// typeScriptType returns the type a getter for a field of kind k returns.
func typeScriptType(k kind) string {
	switch {
	case k.list:
		return typeScriptTypes[k.wire] + "[]"
	case k.angles:
		return "Angles"
	case k.target != "":
		return k.target
	}
	return typeScriptTypes[k.wire]
}
