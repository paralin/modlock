// typeScriptPreamble opens the generated module with the root class and the
// helpers the accessors call and create.
const typeScriptPreamble = `// Code generated by modlock-entitygen. DO NOT EDIT.

import {
  createEntity,
  fireInput,
  readField,
  readFieldList,
  writeField,
  writeFieldList,
  type Angles,
  type EntityOptions,
  type EntityValue,
  type FieldType,
  type FieldValue,
  type KeyValue,
  type Vector,
} from 'modlock'

/** invalidHandle is the handle of no entity. */
const invalidHandle = 0xffffffff

/** CEntityInstance is the root of every entity class: one entity's handle. */
export class CEntityInstance {
  /** handle names the entity, as Pawn.entity does. */
  readonly handle: number

  constructor(handle: number) {
    this.handle = handle
  }
}

/** Class makes an entity class's instance from a handle. */
type Class<C = CEntityInstance> = new (handle: number) => C

/**
 * Each class has a getter and setter per field it adds, and a method per input
 * it accepts. A setter takes its getter's type. Setting undefined leaves a
 * field unchanged, but clears a handle field. A string field is read only,
 * since the host cannot write text. An input method takes its value, if any,
 * then activator, the handle of the entity that caused the input, such as a
 * player's hero; inputs that act on one player, such as
 * LocalPlayerAddCSSClass, act on its player.
 */

/** put writes value to field of className on entity, unless it is undefined. */
function put(entity: CEntityInstance, className: string, field: string, type: FieldType, value: FieldValue | undefined): void {
  if (value !== undefined) {
    writeField(entity.handle, className, field, type, value)
  }
}

/** readAngles reads a vector field of className on entity as pitch, yaw and roll. */
function readAngles(entity: CEntityInstance, className: string, field: string): Angles | undefined {
  const value = readField(entity.handle, className, field, 'vector') as Vector | undefined
  return value === undefined ? undefined : { pitch: value.x, yaw: value.y, roll: value.z }
}

/** putAngles writes value to a vector field of className on entity, unless it is undefined. */
function putAngles(entity: CEntityInstance, className: string, field: string, value: Angles | undefined): void {
  if (value !== undefined) {
    writeField(entity.handle, className, field, 'vector', { x: value.pitch, y: value.yaw, z: value.roll })
  }
}

/** readHandle reads a handle field of className on entity, or undefined when it names no entity. */
function readHandle(entity: CEntityInstance, className: string, field: string): number | undefined {
  const target = readField(entity.handle, className, field, 'handle') as number | undefined
  return target === invalidHandle ? undefined : target
}

/** putHandle writes the handle of value to a handle field of className on entity, or clears it. */
function putHandle(entity: CEntityInstance, className: string, field: string, value: CEntityInstance | undefined): void {
  writeField(entity.handle, className, field, 'handle', value === undefined ? invalidHandle : value.handle)
}

/**
 * KeyType is how one spawn key value travels: as a case of EntityValue, or as
 * angles, which travel as a vector of pitch, yaw and roll.
 */
type KeyType = 'boolean' | 'integer' | 'number' | 'text' | 'vector' | 'color' | 'angles'

/** KeyTypes maps each KeyType to the type of the values it takes. */
interface KeyTypes {
  boolean: boolean
  integer: number
  number: number
  text: string
  vector: Vector
  color: number
  angles: Angles
}

/**
 * KeyMap is one data description: its base and the type of each key it adds.
 * Keys is the type of the key values it and its bases take; spawnKeys is never
 * set and only carries it.
 */
interface KeyMap<Keys = unknown> {
  readonly base: KeyMap | undefined
  readonly keys: Readonly<Record<string, KeyType>>
  readonly spawnKeys?: Keys
}

/** KeysOf is the type of the key values map takes. */
type KeysOf<Map> = Map extends KeyMap<infer Keys> ? Keys : never

/**
 * Designer is a designer name's entry: the class that implements it, its key
 * map and the subclass it needs, if any.
 */
interface Designer<Make extends Class = Class, Keys = unknown> {
  readonly make: Make
  readonly keys: KeyMap<Keys>
  readonly subclass?: string
}

/** Typed is the type of the key values a table of key types takes. */
type Typed<Keys extends Readonly<Record<string, KeyType>>> = { readonly [Key in keyof Keys]?: KeyTypes[Keys[Key]] }

/**
 * Spawn describes an entity create creates: the options of createEntity but
 * the designer name, with typed spawn key values.
 */
export type Spawn<Keys> = Omit<EntityOptions, 'designerName' | 'subclass' | 'team' | 'transmitAlways'> & {
  /**
   * subclass names the entity's game data entry, such as npc_boss_tier1 for
   * the lane Guardian. An NPC needs one.
   */
  subclass?: string
  /** team is the entity's team number; 4 is neutral. */
  team?: number
  /**
   * transmitAlways sends the entity to every client, past the game's own
   * rule, which never sends one without a model, such as a
   * point_clientui_dialog.
   */
  transmitAlways?: boolean
  /** keys are the entity's spawn key values, each typed as the entity reads it. */
  keys?: Keys
}

/** keyValue encodes one typed key value, whose type map or a base gives. */
function keyValue(map: KeyMap | undefined, key: string, value: unknown): KeyValue | undefined {
  for (; map; map = map.base) {
    const type = map.keys[key]
    if (type === 'angles') {
      const angles = value as Angles
      return { key, value: { vector: { x: angles.pitch, y: angles.yaw, z: angles.roll } } }
    }
    if (type) {
      return { key, value: { [type]: value } as EntityValue }
    }
  }
  return undefined
}

/** DesignerName is a designer name create can create. */
export type DesignerName = keyof typeof designers

/** DesignerClass is the class that implements designer name D. */
export type DesignerClass<D extends DesignerName> = InstanceType<(typeof designers)[D]['make']>

/** DesignerKeys is the type of the spawn key values of designer name D. */
export type DesignerKeys<D extends DesignerName> = KeysOf<(typeof designers)[D]['keys']>

/**
 * create creates an entity of designerName from options and addresses it as
 * the class that implements it, or returns undefined when the host refuses.
 */
export function create<D extends DesignerName>(
  designerName: D,
  options: Spawn<DesignerKeys<D>>,
): DesignerClass<D> | undefined {
  const { make, keys: map, subclass } = designers[designerName] as Designer
  const keyValues = [...(options.keyValues ?? [])]
  for (const [key, value] of Object.entries(options.keys ?? {})) {
    const encoded = value === undefined ? undefined : keyValue(map, key, value)
    if (encoded) {
      keyValues.push(encoded)
    }
  }
  const handle = createEntity({
    ...options,
    designerName,
    subclass: options.subclass ?? subclass ?? '',
    team: options.team ?? 0,
    transmitAlways: options.transmitAlways ?? false,
    keyValues,
  })
  return handle === undefined ? undefined : (new make(handle) as DesignerClass<D>)
}
`

