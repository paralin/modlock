// writePython writes the entity classes as one Python module: a class for
// each schema class with its fields annotated and its inputs stubbed for the
// checker, and their entries for the shared accessors; then each data
// description's key value type for the checker and the table create reads;
// then the designer names create takes. It writes the console module beside
// it.
func writePython(s *schema, classes []*class, e *entities, c *console) map[string][]byte {
	// Open with the shared accessors.
	var out bytes.Buffer
	out.WriteString(pythonPreamble)

	// visible maps each class to the type of every field it has, its own and
	// inherited, so a class skips a field whose type conflicts with an
	// inherited one of the same name. The root's handle conflicts with every
	// field.
	visible := map[string]map[string]string{entityRoot: {"handle": ""}}
	names := []string{entityRoot}
	for _, c := range classes[1:] {
		own := map[string]string{}
		for name, typ := range visible[c.base] {
			own[name] = typ
		}
		visible[c.name] = own
		names = append(names, c.name)

		// Gather the fields and inputs the class adds, in declaration order.
		var types, fields, stubs, inputs []string
		for _, f := range s.readableFields(c) {
			typ := pythonType(f.kind)
			if inherited, ok := own[f.name]; ok && inherited != typ || pythonKeywords[f.name] || strings.HasPrefix(f.name, "_") {
				continue
			}
			own[f.name] = typ
			if !f.list {
				typ += " | None"
			}
			types = append(types, fmt.Sprintf("    %s: %s\n", f.name, typ))
			fields = append(fields, fmt.Sprintf("        %q: %q,\n", f.name, luauEntry(f)))
		}
		for _, in := range e.inputs[c.name] {
			method := "input_" + in.name
			if inherited, ok := own[method]; ok && inherited != string(in.value) {
				continue
			}
			own[method] = string(in.value)
			parameter := ""
			if in.value != "" {
				parameter = ", value: " + pythonValues[in.value]
			}
			stub := fmt.Sprintf("        def %s(self%s, activator: int | None = None) -> bool:", method, parameter)
			if doc := sentence(in.description); doc != "" {
				stub += "\n" + wrap("            # ", doc) + "            ...\n"
			} else {
				stub += " ...\n"
			}
			stubs = append(stubs, stub)
			inputs = append(inputs, fmt.Sprintf("        %q: %q,\n", in.name, in.value))
		}

		// Write the class: its annotations, its stubs and its entries.
		fmt.Fprintf(&out, "\n\nclass %s(%s):\n", c.name, c.base)
		body := strings.Join(types, "")
		if len(fields) != 0 {
			body += "    _fields = {\n" + strings.Join(fields, "") + "    }\n"
		}
		if len(inputs) != 0 {
			body += "    _inputs = {\n" + strings.Join(inputs, "") + "    }\n"
			body += "    if TYPE_CHECKING:\n" + strings.Join(stubs, "")
		}
		if body == "" {
			body = "    pass\n"
		}
		out.WriteString(body)
	}

	// Describe each data description's keys as a type for the checker and as
	// the table create reads.
	out.WriteString("\n\nif TYPE_CHECKING:\n    from typing import TypedDict\n")
	var maps []string
	for _, m := range e.keyMaps {
		base, ownBase := "None", "TypedDict"
		if m.base != nil {
			base = fmt.Sprintf("%q", m.base.name)
			ownBase = m.base.name + "Keys"
		}
		var types, cases []string
		for _, k := range m.keys {
			cases = append(cases, fmt.Sprintf("%q: %q", k.name, k.value))
			if !pythonKeywords[k.name] {
				types = append(types, fmt.Sprintf("        %s: %s\n", k.name, pythonValues[k.value]))
			}
		}
		if len(types) == 0 {
			types = []string{"        pass\n"}
		}
		fmt.Fprintf(&out, "\n    class %sKeys(%s, total=False):\n%s", m.name, ownBase, strings.Join(types, ""))
		maps = append(maps, fmt.Sprintf("    %q: (%s, {%s}),\n", m.name, base, strings.Join(cases, ", ")))
	}
	out.WriteString("\n# _KEY_MAPS maps each data description to its base and how each key it adds\n# travels, as a case of EntityValue or as angles.\n")
	out.WriteString("_KEY_MAPS: dict[str, tuple[str | None, dict[str, str]]] = {\n" + strings.Join(maps, "") + "}\n")

	// Name every class for the handle fields.
	out.WriteString("\n# _CLASSES finds each class by name, for the fields that hold a handle.\n_CLASSES: dict[str, type[CEntityInstance]] = {\n")
	for _, name := range names {
		fmt.Fprintf(&out, "    %q: %s,\n", name, name)
	}
	out.WriteString("}\n")

	// Name every designer, and map each to its class, data description and
	// subclass for create.
	designers := make([]string, len(e.designers))
	for i, d := range e.designers {
		designers[i] = d.name
	}
	out.WriteString(pythonLiteral("DesignerName", "DesignerName is a designer name create can create.", designers))
	out.WriteString("\n# _DESIGNERS maps each designer name to the class that implements it, its\n# data description and the subclass it needs, or empty.\n_DESIGNERS: dict[str, tuple[str, str, str]] = {\n")
	for _, d := range e.designers {
		fmt.Fprintf(&out, "    %q: (%q, %q, %q),\n", d.name, d.class, d.keys.name, d.subclass)
	}
	out.WriteString("}\n")
	out.WriteString(pythonCreate)
	return map[string][]byte{"entities.py": out.Bytes(), "console.py": pythonConsole(c)}
}

// pythonConsolePreamble opens the console module with its setters, run,
// apply and the arena preset.
const pythonConsolePreamble = `# Code generated by modlock-entitygen. DO NOT EDIT.

"""console sets the server's console variables and runs its console commands
through modlock.server_command, which may set a development-only or
cheat-protected variable. A mod imports it beside modlock:

    from modlock import console

    console.apply({**console.ARENA, "citadel_allow_duplicate_heroes": True})

Each setter returns False when the host refuses."""

from typing import Literal, TypedDict

from . import server_command


def _format(value: object) -> str:
    """_format returns value as the console reads it: a boolean as 1 or 0 and
    text in quotes."""
    if isinstance(value, bool):
        return "1" if value else "0"
    return f'"{value}"' if isinstance(value, str) else str(value)


def set_boolean(name: BooleanVariable, value: bool) -> bool:
    """set_boolean sets the boolean console variable name to value."""
    return server_command(f"{name} {_format(value)}")


def set_number(name: NumberVariable, value: float) -> bool:
    """set_number sets the numeric console variable name to value."""
    return server_command(f"{name} {_format(value)}")


def set_string(name: StringVariable, value: str) -> bool:
    """set_string sets the string console variable name to value."""
    return server_command(f"{name} {_format(value)}")


def run(name: CommandName, *args: str) -> bool:
    """run runs the console command name with args, each one word of the
    line."""
    return server_command(" ".join((name, *args)))


def apply(settings: Settings) -> list[str]:
    """apply sets each variable in settings, in order, and returns the names
    the host refused, so a mod can log them and play on. Each variable is one
    host call: apply settings when the mod starts or a world loads, not every
    frame."""
    refused: list[str] = []
    for name, value in settings.items():
        if not server_command(f"{name} {_format(value)}"):
            refused.append(name)
    return refused
`

