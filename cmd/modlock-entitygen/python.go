// pythonConsole writes the console module: a literal type of the variables of
// each value type, which its setter takes, one of the commands, which run
// takes, and Settings, a TypedDict of every variable, which apply takes. The
// functional form of TypedDict takes a variable named as a keyword.
func pythonConsole(c *console) []byte {
	// Open with the functions, then name the variables of each value type.
	var out bytes.Buffer
	out.WriteString(pythonConsolePreamble)
	variables := map[string][]string{}
	for _, v := range c.variables {
		variables[v.scriptType()] = append(variables[v.scriptType()], v.name)
	}
	for _, typ := range []string{"boolean", "number", "string"} {
		name := strings.ToUpper(typ[:1]) + typ[1:] + "Variable"
		out.WriteString(pythonLiteral(name, fmt.Sprintf("%s names each %s console variable.", name, typ), variables[typ]))
	}

	// Name the commands.
	commands := make([]string, len(c.commands))
	for i, command := range c.commands {
		commands[i] = command.name
	}
	out.WriteString(pythonLiteral("CommandName", "CommandName names each console command.", commands))

	// Type every variable for apply, then close with the arena preset.
	out.WriteString("\n# Settings holds values for some console variables, each documented with the\n# game's help text.\nSettings = TypedDict(\n    \"Settings\",\n    {\n")
	for _, v := range c.variables {
		if doc := sentence(v.help); doc != "" {
			out.WriteString(wrap("        # ", doc))
		}
		fmt.Fprintf(&out, "        %q: %s,\n", v.name, pythonConsoleTypes[v.scriptType()])
	}
	out.WriteString("    },\n    total=False,\n)\n")
	out.WriteString(pythonArena)
	return out.Bytes()
}

// pythonConsoleTypes maps each script type of a console variable to the
// Python type of its value.
var pythonConsoleTypes = map[string]string{"boolean": "bool", "number": "float", "string": "str"}

// pythonLiteral returns the type alias name, documented by doc, of the
// string literal types of members. A type statement evaluates its value only
// when a checker or a mod asks, so an import costs nothing for it.
func pythonLiteral(name, doc string, members []string) string {
	// Write one member a line.
	var out strings.Builder
	fmt.Fprintf(&out, "\n# %s\ntype %s = Literal[\n", doc, name)
	for _, member := range members {
		fmt.Fprintf(&out, "    %q,\n", member)
	}
	out.WriteString("]\n")
	return out.String()
}

// pythonType returns the type a field of kind k holds.
func pythonType(k kind) string {
	switch {
	case k.list:
		return "list[" + pythonTypes[k.wire] + "]"
	case k.angles:
		return "Angles"
	case k.target != "":
		return k.target
	}
	return pythonTypes[k.wire]
}
