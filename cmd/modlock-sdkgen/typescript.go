// typeScriptPreamble opens the generated module with the vector types and
// their readers.
const typeScriptPreamble = `// Code generated by modlock-sdkgen. DO NOT EDIT.

import * as pb from '../../proto/modlock/wasm.pb.js'
import { call } from './host.js'

/** Vector is a position or direction in the world, in game units. */
export interface Vector {
  x: number
  y: number
  z: number
}

/** Angles is a rotation in degrees. */
export interface Angles {
  pitch: number
  yaw: number
  roll: number
}

/** vector reads a wire vector, taking absent components as zero. */
function vector(value: { x?: number; y?: number; z?: number } | undefined): Vector {
  return { x: value?.x ?? 0, y: value?.y ?? 0, z: value?.z ?? 0 }
}

/** angles reads wire angles, taking absent components as zero. */
function angles(value: { pitch?: number; yaw?: number; roll?: number } | undefined): Angles {
  return { pitch: value?.pitch ?? 0, yaw: value?.yaw ?? 0, roll: value?.roll ?? 0 }
}

/** reply encodes a successful Reply holding response. */
function reply(response?: Uint8Array): Uint8Array {
  return pb.Reply.toBinary({ response })
}

`

// tsWriter writes the TypeScript library's generated module.
type tsWriter struct {
	*directions
	s     *schema
	out   bytes.Buffer
	calls []*call
}

// writeTypeScript returns js/src/host.gen.ts.
func writeTypeScript(s *schema) ([]byte, error) {
	calls, err := s.calls()
	if err != nil {
		return nil, err
	}
	w := &tsWriter{directions: s.directions(calls), s: s, calls: calls}
	w.out.WriteString(typeScriptPreamble)
	if err := w.writeTypes(); err != nil {
		return nil, err
	}
	for _, c := range classes {
		if err := w.writeClass(c); err != nil {
			return nil, err
		}
	}
	for _, c := range calls {
		if c.class == nil {
			if err := w.writeCall(c, ""); err != nil {
				return nil, err
			}
		}
	}
	if err := w.writeMod(); err != nil {
		return nil, err
	}
	return w.out.Bytes(), nil
}

// writeTypes writes the enums and message types in schema order, each with
// the conversions its directions need.
func (w *tsWriter) writeTypes() error {
	for _, e := range w.s.enumOrder {
		if w.enumsIn[e] || w.enumsOut[e] {
			w.writeEnum(e)
		}
	}
	for _, m := range w.s.messageOrder {
		if mapped(m) != "" || (!w.inputs[m] && !w.outputs[m]) {
			continue
		}
		if m.isUnion() {
			if err := w.writeUnion(m); err != nil {
				return err
			}
			continue
		}
		if err := w.writeInterface(m); err != nil {
			return err
		}
	}
	return nil
}

// writeEnum writes an enum as a union of its value names, with the table
// that encodes them when a mod writes it and the table that decodes them
// when a mod reads it.
func (w *tsWriter) writeEnum(e *enum) {
	writeDoc(&w.out, "", e.doc)
	fmt.Fprintf(&w.out, "export type %s =\n", e.name)
	for _, v := range e.named() {
		fmt.Fprintf(&w.out, "  | '%s'\n", e.valueName(v))
	}
	w.out.WriteString("\n")
	if w.enumsIn[e] {
		fmt.Fprintf(&w.out, "/** %sValues encodes each %s. */\n", lowerCamel(e.name), e.name)
		fmt.Fprintf(&w.out, "const %sValues: Record<%s, pb.%s> = {\n", lowerCamel(e.name), e.name, e.name)
		for _, v := range e.named() {
			fmt.Fprintf(&w.out, "  %s: %d,\n", e.valueName(v), v.number)
		}
		w.out.WriteString("}\n\n")
	}
	if w.enumsOut[e] {
		fmt.Fprintf(&w.out, "/** %sNames decodes each %s; an unknown value has no name. */\n", lowerCamel(e.name), e.name)
		fmt.Fprintf(&w.out, "const %sNames: Partial<Record<number, %s>> = {\n", lowerCamel(e.name), e.name)
		for _, v := range e.named() {
			fmt.Fprintf(&w.out, "  %d: '%s',\n", v.number, e.valueName(v))
		}
		w.out.WriteString("}\n\n")
	}
}

// writeUnion writes a message holding only a oneof as a union type, with
// its conversions.
func (w *tsWriter) writeUnion(m *message) error {
	o := m.oneofs[0]
	if o.keyed {
		w.writeKeyedUnion(m)
		return nil
	}
	writeDoc(&w.out, "", m.doc)
	fmt.Fprintf(&w.out, "export type %s = %s\n\n", m.name, w.oneofType(o))
	if w.inputs[m] {
		value, err := w.oneofValue(o, "value")
		if err != nil {
			return err
		}
		fmt.Fprintf(&w.out, "/** to%s encodes %s. */\n", m.name, article(m.name))
		fmt.Fprintf(&w.out, "function to%s(value: %s): pb.%s {\n  return { %s: %s }\n}\n\n", m.name, m.name, m.name, lowerCamel(o.name), value)
	}
	if w.outputs[m] {
		fmt.Fprintf(&w.out, "/** from%s decodes %s, or undefined when it holds none. */\n", m.name, article(m.name))
		fmt.Fprintf(&w.out, "function from%s(message: pb.%s | undefined): %s | undefined {\n", m.name, m.name, m.name)
		fmt.Fprintf(&w.out, "  const value = message?.%s\n", lowerCamel(o.name))
		w.out.WriteString("  if (value === undefined || value.case === undefined) return undefined\n")
		var cases []string
		for _, f := range o.fields {
			if read := w.fromValue(f, "value.value"); read != "value.value" {
				cases = append(cases, fmt.Sprintf("    case '%s':\n      return %s\n", lowerCamel(f.name), read))
			}
		}
		if len(cases) != 0 {
			w.out.WriteString("  switch (value.case) {\n" + strings.Join(cases, "") + "  }\n")
		}
		w.out.WriteString("  return value.value\n}\n\n")
	}
	return nil
}

// writeKeyedUnion writes a keyed union as a union of objects that each hold
// one case by its name, with its conversions.
func (w *tsWriter) writeKeyedUnion(m *message) {
	o := m.oneofs[0]
	writeDoc(&w.out, "", m.doc)
	fmt.Fprintf(&w.out, "export type %s =\n", m.name)
	for _, f := range o.fields {
		fmt.Fprintf(&w.out, "  | { readonly %s: %s }\n", lowerCamel(f.name), w.tsBase(f))
	}
	w.out.WriteString("\n")
	if w.inputs[m] {
		fmt.Fprintf(&w.out, "/** to%s encodes %s. */\n", m.name, article(m.name))
		fmt.Fprintf(&w.out, "function to%s(value: %s): pb.%s {\n", m.name, m.name, m.name)
		last := o.fields[len(o.fields)-1]
		for _, f := range o.fields {
			name := lowerCamel(f.name)
			encoded := fmt.Sprintf("{ %s: { case: '%s', value: %s } }", lowerCamel(o.name), name, w.toValue(f, "value."+name))
			if f == last {
				fmt.Fprintf(&w.out, "  return %s\n", encoded)
				continue
			}
			fmt.Fprintf(&w.out, "  if ('%s' in value) return %s\n", name, encoded)
		}
		w.out.WriteString("}\n\n")
	}
	if w.outputs[m] {
		fmt.Fprintf(&w.out, "/** from%s decodes %s, or undefined when it holds none. */\n", m.name, article(m.name))
		fmt.Fprintf(&w.out, "function from%s(message: pb.%s | undefined): %s | undefined {\n", m.name, m.name, m.name)
		fmt.Fprintf(&w.out, "  const value = message?.%s\n  switch (value?.case) {\n", lowerCamel(o.name))
		for _, f := range o.fields {
			name := lowerCamel(f.name)
			fmt.Fprintf(&w.out, "    case '%s':\n      return { %s: %s }\n", name, name, w.fromValue(f, "value.value"))
		}
		w.out.WriteString("  }\n  return undefined\n}\n\n")
	}
}

// writeInterface writes a message as an interface, with the conversions its
// directions need.
func (w *tsWriter) writeInterface(m *message) error {
	outputOnly := w.outputs[m] && !w.inputs[m]
	readonly := ""
	if outputOnly {
		readonly = "readonly "
	}
	fields := w.interfaceFields(m)
	writeDoc(&w.out, "", m.doc)
	fmt.Fprintf(&w.out, "export interface %s {\n", m.name)
	for _, f := range fields {
		if o := f.oneof; o != nil {
			if o.fields[0] == f {
				writeDoc(&w.out, "  ", fieldDoc(m, rename(o.doc, camel(o.name), lowerCamel(o.name))))
				fmt.Fprintf(&w.out, "  %s%s?: %s\n", readonly, lowerCamel(o.name), w.oneofType(o))
			}
			continue
		}
		writeDoc(&w.out, "  ", fieldDoc(m, f.doc))
		mark := ""
		if f.optional || (f.repeated && !outputOnly) || (f.enum != nil && !f.repeated && w.outputs[m]) {
			mark = "?"
		}
		fieldType := w.tsType(f)
		if w.inputs[m] {
			fieldType = w.tsInput(f)
		}
		fmt.Fprintf(&w.out, "  %s%s%s: %s\n", readonly, lowerCamel(f.name), mark, fieldType)
	}
	w.out.WriteString("}\n\n")

	if w.inputs[m] && w.converts(m) {
		fmt.Fprintf(&w.out, "/** to%s encodes %s. */\n", m.name, article(m.name))
		fmt.Fprintf(&w.out, "function to%s(value: %s): pb.%s {\n  return {\n", m.name, m.name, m.name)
		for _, f := range fields {
			if o := f.oneof; o != nil {
				if o.fields[0] == f {
					name := "value." + lowerCamel(o.name)
					encoded, err := w.oneofValue(o, name)
					if err != nil {
						return err
					}
					fmt.Fprintf(&w.out, "    %s: %s === undefined ? undefined : %s,\n", lowerCamel(o.name), name, encoded)
				}
				continue
			}
			fmt.Fprintf(&w.out, "    %s: %s,\n", lowerCamel(f.name), w.toField(f, "value."+lowerCamel(f.name)))
		}
		w.out.WriteString("  }\n}\n\n")
	}
	if w.outputs[m] {
		fmt.Fprintf(&w.out, "/** from%s decodes %s. */\n", m.name, article(m.name))
		fmt.Fprintf(&w.out, "function from%s(message: pb.%s): %s {\n  return {\n", m.name, m.name, m.name)
		for _, f := range fields {
			if o := f.oneof; o != nil {
				if o.fields[0] == f {
					for _, c := range o.fields {
						if w.fromValue(c, "v") != "v" {
							return fmt.Errorf("%s: oneof %s needs a decoded case", m.name, o.name)
						}
					}
					fmt.Fprintf(&w.out, "    %s: message.%s?.value,\n", lowerCamel(o.name), lowerCamel(o.name))
				}
				continue
			}
			fmt.Fprintf(&w.out, "    %s: %s,\n", lowerCamel(f.name), w.fromField(f, "message."+lowerCamel(f.name)))
		}
		w.out.WriteString("  }\n}\n\n")
	}
	return nil
}

// interfaceFields returns the fields of m a mod sees.
func (w *tsWriter) interfaceFields(m *message) []*field {
	var fields []*field
	for _, f := range m.fields {
		if f != w.omitted[m] {
			fields = append(fields, f)
		}
	}
	return fields
}

// converts reports whether encoding a value of m changes it, so m needs a
// to function. A repeated field converts because a mod may pass a read-only
// array, which the encoder copies.
func (w *tsWriter) converts(m *message) bool {
	if m.isUnion() {
		return true
	}
	if w.omitted[m] != nil || len(m.oneofs) != 0 {
		return true
	}
	for _, f := range m.fields {
		if f.repeated || w.toValue(f, "v") != "v" {
			return true
		}
	}
	return false
}

// writeClass writes one class with its calls as methods.
func (w *tsWriter) writeClass(c *class) error {
	writeDoc(&w.out, "", c.doc)
	fmt.Fprintf(&w.out, "export class %s {\n", c.name)
	writeDoc(&w.out, "  ", c.keyDoc)
	fmt.Fprintf(&w.out, "  readonly %s: number\n\n", c.key)
	fmt.Fprintf(&w.out, "  constructor(%s: number) {\n    this.%s = %s\n  }\n", c.key, c.key, c.key)
	for _, call := range w.calls {
		if call.class == c {
			w.out.WriteString("\n")
			if err := w.writeCall(call, "  "); err != nil {
				return err
			}
		}
	}
	w.out.WriteString("}\n\n")
	return nil
}

// writeCall writes one call as a method when indent is set, or else as an
// exported function.
func (w *tsWriter) writeCall(c *call, indent string) error {
	// Declare the call.
	var params []string
	switch {
	case c.options:
		params = []string{"options: " + c.method.request.name}
	default:
		for _, p := range c.params {
			mark := ""
			if p.optional {
				mark = "?"
			}
			params = append(params, fmt.Sprintf("%s%s: %s", p.name, mark, w.paramType(p)))
		}
	}
	result, failure := w.resultType(c)
	writeDoc(&w.out, indent, rename(c.method.doc, c.method.name, c.name))
	declare := "export function "
	if indent != "" {
		declare = ""
	}
	fmt.Fprintf(&w.out, "%s%s%s(%s): %s {\n", indent, declare, c.name, strings.Join(params, ", "), result)

	// Encode the request.
	request, err := w.request(c)
	if err != nil {
		return err
	}
	body := indent + "  "
	send := fmt.Sprintf("call('%s', %s)", c.method.name, request)
	if c.result == nil {
		fmt.Fprintf(&w.out, "%sreturn %s !== undefined\n%s}\n", body, send, indent)
		if indent == "" {
			w.out.WriteString("\n")
		}
		return nil
	}

	// Decode the response.
	fmt.Fprintf(&w.out, "%sconst reply = %s\n", body, send)
	fmt.Fprintf(&w.out, "%sif (reply === undefined) return %s\n", body, failure)
	fmt.Fprintf(&w.out, "%sconst response = pb.%s.fromBinary(reply)\n", body, c.method.response.name)
	value := "response." + lowerCamel(c.result.name)
	read := w.fromField(c.result, value)
	if f := c.result; f.message != nil && !f.repeated && !f.optional && !f.message.isUnion() {
		read = fmt.Sprintf("%s === undefined ? undefined : %s", value, w.fromValue(f, value))
	}
	fmt.Fprintf(&w.out, "%sreturn %s\n%s}\n", body, read, indent)
	if indent == "" {
		w.out.WriteString("\n")
	}
	return nil
}

// request returns the expression that encodes c's request.
func (w *tsWriter) request(c *call) (string, error) {
	m := c.method.request
	if m.isEmpty() {
		return "new Uint8Array()", nil
	}
	var members []string
	if c.receiver != nil {
		members = append(members, fmt.Sprintf("%s: this.%s", lowerCamel(c.receiver.name), c.class.key))
	}
	switch {
	case c.options && c.receiver == nil && w.converts(m):
		return fmt.Sprintf("pb.%s.toBinary(to%s(options))", m.name, m.name), nil
	case c.options && c.receiver == nil:
		return fmt.Sprintf("pb.%s.toBinary(options)", m.name), nil
	case c.options:
		members = append(members, fmt.Sprintf("...to%s(options)", m.name))
	default:
		for _, p := range c.params {
			value := p.name
			if p.oneof != nil {
				v, err := w.oneofValue(p.oneof, p.name)
				if err != nil {
					return "", err
				}
				value = v
			} else {
				value = w.toField(p.field, p.name)
			}
			name := lowerCamel(p.name)
			if p.field != nil {
				name = lowerCamel(p.field.name)
			}
			if value == name {
				members = append(members, name)
			} else {
				members = append(members, name+": "+value)
			}
		}
	}
	return fmt.Sprintf("pb.%s.toBinary({ %s })", m.name, strings.Join(members, ", ")), nil
}

// resultType returns the type a call returns and the value it returns when
// the call fails.
func (w *tsWriter) resultType(c *call) (string, string) {
	f := c.result
	switch {
	case f == nil:
		return "boolean", "false"
	case f.repeated:
		return w.tsType(f), "[]"
	case f.kind == descriptorpb.FieldDescriptorProto_TYPE_BOOL && !f.optional:
		return "boolean", "false"
	}
	return w.tsBase(f) + " | undefined", "undefined"
}

// paramType returns the type of one positional parameter.
func (w *tsWriter) paramType(p *param) string {
	if p.oneof == nil {
		return w.tsInput(p.field)
	}
	return w.oneofType(p.oneof)
}

// oneofType returns the union of the types of o's cases.
func (w *tsWriter) oneofType(o *oneof) string {
	var types []string
	for _, f := range o.fields {
		types = append(types, w.tsBase(f))
	}
	return strings.Join(types, " | ")
}

// oneofValue returns the expression that encodes value, of one of o's
// cases' types, as o's wire form. Each case must differ in its typeof.
func (w *tsWriter) oneofValue(o *oneof, value string) (string, error) {
	seen := map[string]bool{}
	expr := ""
	for _, f := range slices.Backward(o.fields) {

		kind := typeOf(f)
		if seen[kind] {
			return "", fmt.Errorf("oneof %s has two cases of typeof %s", o.name, kind)
		}
		seen[kind] = true
		encoded := fmt.Sprintf("{ case: '%s' as const, value: %s }", lowerCamel(f.name), w.toValue(f, value))
		if expr == "" {
			expr = encoded
			continue
		}
		expr = fmt.Sprintf("typeof %s === '%s' ? %s : %s", value, kind, encoded, expr)
	}
	return expr, nil
}

// typeOf returns what JavaScript's typeof answers for a value of f.
func typeOf(f *field) string {
	switch f.kind {
	case descriptorpb.FieldDescriptorProto_TYPE_BOOL:
		return "boolean"
	case descriptorpb.FieldDescriptorProto_TYPE_STRING:
		return "string"
	case descriptorpb.FieldDescriptorProto_TYPE_MESSAGE, descriptorpb.FieldDescriptorProto_TYPE_BYTES:
		return "object"
	}
	if is64(f) {
		return "bigint"
	}
	return "number"
}

// tsType returns the TypeScript type of a field, repeated or not.
func (w *tsWriter) tsType(f *field) string {
	if f.repeated {
		return w.tsBase(f) + "[]"
	}
	return w.tsBase(f)
}

// tsInput returns the TypeScript type a mod passes for a field, which takes a
// read-only array for a repeated one.
func (w *tsWriter) tsInput(f *field) string {
	if f.repeated {
		return "readonly " + w.tsBase(f) + "[]"
	}
	return w.tsBase(f)
}

// tsBase returns the TypeScript type of one value of a field.
func (w *tsWriter) tsBase(f *field) string {
	if c := classOf(f); c != nil {
		return c.name
	}
	switch {
	case f.message != nil:
		if name := mapped(f.message); name != "" {
			return name
		}
		return f.message.name
	case f.enum != nil:
		return f.enum.name
	case f.kind == descriptorpb.FieldDescriptorProto_TYPE_BOOL:
		return "boolean"
	case f.kind == descriptorpb.FieldDescriptorProto_TYPE_STRING:
		return "string"
	case f.kind == descriptorpb.FieldDescriptorProto_TYPE_BYTES:
		return "Uint8Array"
	case is64(f):
		return "bigint"
	}
	return "number"
}

// zero returns the TypeScript value of an unset scalar field.
func zero(f *field) string {
	switch {
	case f.kind == descriptorpb.FieldDescriptorProto_TYPE_BOOL:
		return "false"
	case f.kind == descriptorpb.FieldDescriptorProto_TYPE_STRING:
		return "''"
	case f.kind == descriptorpb.FieldDescriptorProto_TYPE_BYTES:
		return "new Uint8Array()"
	case is64(f):
		return "0n"
	}
	return "0"
}

// fromValue returns the expression that decodes value, one present wire
// value of f.
func (w *tsWriter) fromValue(f *field, value string) string {
	if c := classOf(f); c != nil {
		return fmt.Sprintf("new %s(%s)", c.name, value)
	}
	if f.enum != nil {
		return fmt.Sprintf("%sNames[%s]", lowerCamel(f.enum.name), value)
	}
	if f.message == nil {
		return value
	}
	switch mapped(f.message) {
	case "Vector":
		return fmt.Sprintf("vector(%s)", value)
	case "Angles":
		return fmt.Sprintf("angles(%s)", value)
	}
	return fmt.Sprintf("from%s(%s)", f.message.name, value)
}

// fromField returns the expression that decodes value, the wire field f,
// filling an unset field with its zero.
func (w *tsWriter) fromField(f *field, value string) string {
	switch {
	case f.repeated && f.enum != nil:
		return fmt.Sprintf("(%s ?? []).flatMap((v) => %s ?? [])", value, w.fromValue(f, "v"))
	case f.repeated:
		if read := w.fromValue(f, "v"); read != "v" {
			return fmt.Sprintf("(%s ?? []).map((v) => %s)", value, read)
		}
		return value + " ?? []"
	case f.optional:
		if read := w.fromValue(f, value); read != value {
			return fmt.Sprintf("%s === undefined ? undefined : %s", value, read)
		}
		return value
	case f.message != nil && f.message.isUnion():
		return w.fromValue(f, value)
	case f.message != nil && mapped(f.message) != "":
		return w.fromValue(f, value)
	case f.message != nil:
		return w.fromValue(f, value+" ?? {}")
	}
	return w.fromValue(f, value+" ?? "+zero(f))
}

// toValue returns the expression that encodes value, one value of f.
func (w *tsWriter) toValue(f *field, value string) string {
	if c := classOf(f); c != nil {
		return value + "." + c.key
	}
	switch {
	case f.enum != nil:
		return fmt.Sprintf("%sValues[%s]", lowerCamel(f.enum.name), value)
	case f.message != nil && mapped(f.message) == "" && w.converts(f.message):
		return fmt.Sprintf("to%s(%s)", f.message.name, value)
	}
	return value
}

// toField returns the expression that encodes value, the field f, which may
// be undefined when f may be omitted.
func (w *tsWriter) toField(f *field, value string) string {
	encoded := w.toValue(f, "v")
	switch {
	case f.repeated && encoded != "v":
		return fmt.Sprintf("%s?.map((v) => %s)", value, encoded)
	case f.repeated:
		return value + "?.slice()"
	case f.optional && encoded != "v":
		return fmt.Sprintf("%s === undefined ? undefined : %s", value, w.toValue(f, value))
	}
	return w.toValue(f, value)
}

// writeMod writes the interface the mod's event handlers implement and the
// dispatch that runs them.
func (w *tsWriter) writeMod() error {
	writeDoc(&w.out, "", "ModHandlers handles the events the game delivers to the mod.")
	w.out.WriteString("export interface ModHandlers {\n")
	for _, m := range w.s.mod.methods {
		writeDoc(&w.out, "  ", rename(m.doc, m.name, lowerCamel(m.name)))
		param := ""
		if !m.request.isEmpty() {
			param = "event: " + m.request.name
		}
		result := "void"
		if !m.response.isEmpty() {
			result = m.response.name
		}
		fmt.Fprintf(&w.out, "  %s(%s): %s\n", lowerCamel(m.name), param, result)
	}
	w.out.WriteString("}\n\n")

	writeDoc(&w.out, "", "serveMod runs the encoded Call in bytes on handlers and returns the encoded\nReply. A handler that throws answers with its error.")
	w.out.WriteString("export function serveMod(handlers: ModHandlers, bytes: Uint8Array): Uint8Array {\n")
	w.out.WriteString("  const request = pb.Call.fromBinary(bytes)\n")
	w.out.WriteString("  const input = request.request ?? new Uint8Array()\n")
	w.out.WriteString("  try {\n    switch (request.method) {\n")
	for _, m := range w.s.mod.methods {
		event := ""
		if !m.request.isEmpty() {
			event = fmt.Sprintf("from%s(pb.%s.fromBinary(input))", m.request.name, m.request.name)
		}
		handle := fmt.Sprintf("handlers.%s(%s)", lowerCamel(m.name), event)
		fmt.Fprintf(&w.out, "      case '%s':\n", m.name)
		if m.response.isEmpty() {
			fmt.Fprintf(&w.out, "        %s\n        return reply()\n", handle)
			continue
		}
		if w.converts(m.response) {
			handle = fmt.Sprintf("to%s(%s)", m.response.name, handle)
		}
		fmt.Fprintf(&w.out, "        return reply(pb.%s.toBinary(%s))\n", m.response.name, handle)
	}
	w.out.WriteString("    }\n  } catch (error) {\n    return pb.Reply.toBinary({ error: String(error) })\n  }\n")
	w.out.WriteString("  return pb.Reply.toBinary({ error: `the mod has no method ${request.method}` })\n}\n")
	return nil
}

// writeDoc writes text as a JSDoc comment at indent.
func writeDoc(out *bytes.Buffer, indent, text string) {
	if text == "" {
		return
	}
	if !strings.Contains(text, "\n") && len(indent)+len(text) <= 72 {
		fmt.Fprintf(out, "%s/** %s */\n", indent, text)
		return
	}
	fmt.Fprintf(out, "%s/**\n", indent)
	writeComment(out, indent, " *", text)
	fmt.Fprintf(out, "%s */\n", indent)
}

// mapped returns the name of the library type a message maps to, or empty
// for a message the generator writes.
func mapped(m *message) string {
	switch m.full {
	case ".modlock.Vec3":
		return "Vector"
	case ".modlock.EulerAngles":
		return "Angles"
	}
	return ""
}

// is64 reports whether f holds a 64-bit integer.
func is64(f *field) bool {
	switch f.kind {
	case descriptorpb.FieldDescriptorProto_TYPE_INT64, descriptorpb.FieldDescriptorProto_TYPE_UINT64,
		descriptorpb.FieldDescriptorProto_TYPE_SINT64, descriptorpb.FieldDescriptorProto_TYPE_FIXED64,
		descriptorpb.FieldDescriptorProto_TYPE_SFIXED64:
		return true
	}
	return false
}

// article returns name after the indefinite article it takes.
func article(name string) string {
	if strings.ContainsRune("AEIOU", rune(name[0])) {
		return "an " + name
	}
	return "a " + name
}

// fieldDoc returns doc, a comment in m, with the schema's names of m's fields
// in their TypeScript form.
func fieldDoc(m *message, doc string) string {
	for _, f := range m.fields {
		doc = regexp.MustCompile(`\b`+camel(f.name)+`\b`).ReplaceAllString(doc, lowerCamel(f.name))
	}
	return doc
}
