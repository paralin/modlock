// cppPreamble opens src/wasm/host_service.gen.h.
const cppPreamble = `// Code generated by modlock-sdkgen. DO NOT EDIT.

#pragma once

#include <expected>
#include <functional>
#include <string>
#include <string_view>
#include <type_traits>
#include <unordered_map>
#include <utility>

#include "proto/modlock/wasm.pb.h"

namespace modlock::wasm {

namespace detail {

// Fail returns a reply carrying error.
inline Reply Fail(std::string error) {
  Reply reply;
  reply.set_error(std::move(error));
  return reply;
}

// Answer returns the reply to a call that returns nothing.
inline Reply Answer(const std::expected<void, std::string>& result) {
  return result ? Reply{} : Fail(result.error());
}

// Answer returns the reply carrying a call's response or error.
template <typename Response>
Reply Answer(const std::expected<Response, std::string>& result) {
  if (!result) {
    return Fail(result.error());
  }
  Reply reply;
  reply.set_response(result->SerializeAsString());
  return reply;
}

}  // namespace detail

`

// writeCpp returns src/wasm/host_service.gen.h.
func writeCpp(s *schema) ([]byte, error) {
	var out bytes.Buffer
	out.WriteString(cppPreamble)

	// Declare the host's service.
	writeComment(&out, "", "//", s.host.doc)
	out.WriteString("//\n// HostService declares one virtual method per call. Each returns that the\n")
	out.WriteString("// host does not support the call until a subclass overrides it.\nclass HostService {\n public:\n")
	out.WriteString("  virtual ~HostService() = default;\n\n")
	for _, m := range s.host.methods {
		writeComment(&out, "  ", "//", m.doc)
		fmt.Fprintf(&out, "  virtual %s %s(%s) {\n", cppResult(m), m.name, cppParam(m, "/*request*/"))
		fmt.Fprintf(&out, "    return std::unexpected(%q);\n  }\n\n", "this host does not support "+m.name)
	}
	out.WriteString("  // Dispatch runs call on the method it names and returns the reply.\n")
	out.WriteString("  Reply Dispatch(const Call& call) {\n")
	out.WriteString("    using Handler = Reply (*)(HostService&, const std::string&);\n")
	out.WriteString("    static const std::unordered_map<std::string_view, Handler> handlers = {\n")
	for _, m := range s.host.methods {
		fmt.Fprintf(&out, "        {%q,\n         [](HostService& host, const std::string& bytes) {\n", m.name)
		if m.request.isEmpty() {
			fmt.Fprintf(&out, "           static_cast<void>(bytes);\n           return detail::Answer(host.%s());\n         }},\n", m.name)
			continue
		}
		fmt.Fprintf(&out, "           %s request;\n", cppType(m.request))
		fmt.Fprintf(&out, "           if (!request.ParseFromString(bytes)) {\n             return detail::Fail(%q);\n           }\n",
			"the "+m.name+" request is malformed")
		fmt.Fprintf(&out, "           return detail::Answer(host.%s(request));\n         }},\n", m.name)
	}
	out.WriteString("    };\n")
	out.WriteString("    const auto handler = handlers.find(call.method());\n")
	out.WriteString("    if (handler == handlers.end()) {\n")
	out.WriteString("      return detail::Fail(\"this host has no method \" + call.method());\n    }\n")
	out.WriteString("    return handler->second(*this, call.request());\n  }\n};\n\n")

	// Declare the client that delivers events to a mod.
	writeComment(&out, "", "//", s.mod.doc)
	out.WriteString("//\n// ModClient sends each event to the mod through a transport that delivers\n")
	out.WriteString("// one call and returns the mod's reply.\nclass ModClient {\n public:\n")
	out.WriteString("  using Transport = std::function<std::expected<Reply, std::string>(const Call&)>;\n\n")
	out.WriteString("  explicit ModClient(Transport transport) : transport_(std::move(transport)) {}\n\n")
	for _, m := range s.mod.methods {
		writeComment(&out, "  ", "//", m.doc)
		response, request := "void", "Empty{}"
		if !m.response.isEmpty() {
			response = cppType(m.response)
		}
		if !m.request.isEmpty() {
			request = "event"
		}
		fmt.Fprintf(&out, "  %s %s(%s) {\n", cppResult(m), m.name, cppParam(m, "event"))
		fmt.Fprintf(&out, "    return Send<%s>(%q, %s);\n  }\n\n", response, m.name, request)
	}
	out.WriteString(` private:
  // Send delivers one call and decodes the mod's response.
  template <typename Response, typename Request>
  std::expected<Response, std::string> Send(std::string_view method, const Request& request) {
    Call call;
    call.set_method(method);
    call.set_request(request.SerializeAsString());
    auto reply = transport_(call);
    if (!reply) {
      return std::unexpected(std::move(reply.error()));
    }
    if (!reply->error().empty()) {
      return std::unexpected(reply->error());
    }
    if constexpr (std::is_void_v<Response>) {
      return {};
    } else {
      Response response;
      if (!response.ParseFromString(reply->response())) {
        return std::unexpected("the mod's " + std::string(method) + " response is malformed");
      }
      return response;
    }
  }

  Transport transport_;
};

}  // namespace modlock::wasm
`)
	return out.Bytes(), nil
}

// cppResult returns the return type of a method.
func cppResult(m *method) string {
	if m.response.isEmpty() {
		return "std::expected<void, std::string>"
	}
	return fmt.Sprintf("std::expected<%s, std::string>", cppType(m.response))
}

// cppParam returns the parameter list of a method, naming its request name.
func cppParam(m *method, name string) string {
	if m.request.isEmpty() {
		return ""
	}
	return fmt.Sprintf("const %s& %s", cppType(m.request), name)
}

// cppType returns the C++ name of a message, qualified when it lies outside
// the header's namespace.
func cppType(m *message) string {
	if name, ok := strings.CutPrefix(m.full, ".modlock.wasm."); ok {
		return strings.ReplaceAll(name, ".", "_")
	}
	return strings.ReplaceAll(m.full, ".", "::")
}
