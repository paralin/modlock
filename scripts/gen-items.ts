// gen-items writes js/src/items.gen.ts, the table of the shop's items, from
// the game's abilities.vdata in an extracted copy of its files, such as a
// GameTracking-Deadlock checkout:
//
//   bun scripts/gen-items.ts <game-files>
//
// An item is a block of abilities.vdata whose ability type is an item, with a
// shop slot, a tier and an icon, and which the game has not disabled.
import { resolve } from 'node:path'

import { itemId } from '../js/src/item-id.js'

const [files] = process.argv.slice(2)
if (!files) {
  throw new Error('Usage: bun scripts/gen-items.ts <game-files>')
}
const vdata = await Bun.file(
  resolve(files, 'game/citadel/pak01_dir/scripts/abilities.vdata'),
).text()

// slots maps the game's slot types to the names players read on the shop's
// tabs.
const slots: Record<string, string> = {
  EItemSlotType_WeaponMod: 'weapon',
  EItemSlotType_Armor: 'vitality',
  EItemSlotType_Tech: 'spirit',
}

// Read each top-level block's fields.
const rows: string[] = []
for (const block of vdata.split(/^\t(?=[A-Za-z0-9_]+ = *$)/m)) {
  // Take only the shop's enabled items.
  const field = (name: string) =>
    new RegExp(`^\\t\\t${name} = (.+)$`, 'm').exec(block)?.[1]?.trim()
  const name = /^([A-Za-z0-9_]+) = *$/m.exec(block)?.[1]
  const slot = slots[field('m_eItemSlotType')?.replaceAll('"', '') ?? '']
  const tier = /EModTier_(\d)/.exec(field('m_iItemTier') ?? '')?.[1]
  const icon = /panorama:"([^"]+)"/.exec(field('m_strAbilityImage') ?? '')?.[1]
  const disabled = /^(true|1)$/.test(field('m_bDisabled') ?? '')
  if (
    !name ||
    field('m_eAbilityType') !== '"EAbilityType_Item"' ||
    !slot ||
    !tier ||
    !icon ||
    disabled
  ) {
    continue
  }

  // An active item casts; an imbuing one strengthens an ability it is put on.
  const active = !/PASSIVE/.test(field('m_eAbilityActivation') ?? '')
  const imbue = /IMBUE/.test(field('m_TargetAbilityEffectsToApply') ?? '')
  rows.push(
    `  { name: '${name}', id: ${itemId(name)}, slot: '${slot}', tier: ${tier}, active: ${active}, imbue: ${imbue}, icon: '${icon}' },`,
  )
}
if (rows.length < 100) {
  throw new Error(`only ${rows.length} items in abilities.vdata`)
}
rows.sort()

// Write the table.
await Bun.write(
  new URL('../js/src/items.gen.ts', import.meta.url),
  `// Code generated by scripts/gen-items.ts from the game's abilities.vdata. DO NOT EDIT.

import type { Item } from './items.js'

/** itemTable lists the shop's items by class name. */
export const itemTable: readonly Item[] = [
${rows.join('\n')}
]
`,
)
console.log(`${rows.length} items`)
